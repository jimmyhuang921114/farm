/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_ETH_Init();
  MX_USART3_UART_Init();
  MX_USB_OTG_FS_PCD_Init();




  /* USER CODE BEGIN 2 */
  UART_Sender_Init(&huart3);
  Track_Clear();

  if (UART_Receiver_Start(&huart3) != HAL_OK)
  {
      Error_Handler();
  }

  uint32_t last_track_ms = HAL_GetTick();
  /* USER CODE END 2 */




  /* Infinite loop */
  /* USER CODE BEGIN WHILE */

  while (1)
  {
      // 1. 處理 UART 接收
      UART_Receiver_Process();

      RobotCommand rx_command;

      if (UART_Receiver_TakeCommand(&rx_command))
      {
          if (rx_command.type == COMMAND_PERSON_POSITION)
          {
              // 將 XYZ 傳給 track.c
              Track_SetPosition(
                  rx_command.person.x,
                  rx_command.person.y,
                  rx_command.person.z
              );
          }
          else
          {
              // STOP 或 PERSON_LOST
              Track_Clear();
          }
      }

      // 2. 每 20 ms 執行追蹤演算法
      uint32_t now = HAL_GetTick();
      uint32_t elapsed = now - last_track_ms;

      if (elapsed >= 20U)
      {
          last_track_ms = now;

          float dt = elapsed / 1000.0f;

          // 計算追蹤指令
          Track_Update(dt);

          // 取得線速度與角速度
          TrackCommand result = Track_GetCommand();

          float v = result.linear_vel;
          float w = result.angular_vel;

          // 3. 將 v、w 封裝為 JSON
          char reply[160];

          int length = snprintf(
              reply,
              sizeof(reply),
              "{\"cmd\":\"cmd_vel\",\"data\":{\"v\":%.4f,\"w\":%.4f}}\n",
              (double)v,
              (double)w
          );

          // 4. 經 UART 回傳 Python Bridge
          if (length > 0 && length < (int)sizeof(reply))
          {
              UART_Sender_Send(reply);
          }
      }
  }

}
